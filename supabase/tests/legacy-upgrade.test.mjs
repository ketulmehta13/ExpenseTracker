await db.exec(migration('20260819000001_subscriptions.sql'));
await db.exec(migration('20261017000000_phase0_fixes.sql'));
await db.exec(migration('20261017000000_phase0_fixes.sql')); // must be re-runnable

console.log('Production replica after ai_tables -> subscriptions -> phase0:');

await check('categories gains color, icon and created_at; profiles gains updated_at', async () => {
  const { rows } = await db.query(
    `SELECT table_name, column_name FROM information_schema.columns
     WHERE table_schema = 'public' AND ((table_name = 'categories' AND column_name IN ('color', 'icon', 'created_at'))
        OR (table_name = 'profiles' AND column_name = 'updated_at'))`,
  );
  assert.equal(rows.length, 4);
});

await check('the 8 existing default categories are kept as-is (no re-seed)', async () => {
  const { rows } = await db.query(`SELECT name FROM categories WHERE user_id IS NULL ORDER BY name`);
  assert.deepEqual(rows.map((r) => r.name), ['Entertainment', 'Food', 'Other', 'Rent', 'Salary', 'Shopping', 'Travel', 'Utilities']);
});

await check('both transactions still point at Food', async () => {
  const row = await one(`SELECT count(*)::int AS n FROM transactions t JOIN categories c ON c.id = t.category_id WHERE c.name = 'Food'`);
  assert.equal(row.n, 2);
});

await check('one unique constraint remains: (name, user_id) NULLS NOT DISTINCT', async () => {
  const { rows } = await db.query(
    `SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = 'public.categories'::regclass AND contype = 'u'`,
  );
  assert.equal(rows.length, 1);
  assert.equal(rows[0].conname, 'categories_name_user_unique');
  assert.match(rows[0].def, /NULLS NOT DISTINCT/);
});

await check('a duplicate default category can no longer be inserted', async () => {
  await assert.rejects(db.query(`INSERT INTO categories (name, user_id) VALUES ('Food', NULL)`), /duplicate key/);
});

await check('the app can create a custom category (color + icon, user_id from the caller)', async () => {
  const row = await asRole('authenticated', ALICE, async () =>
    one(`INSERT INTO categories (name, color, icon, user_id) VALUES ('Coffee', '#0d3a35', '☕', $1) RETURNING user_id, color, icon`, [ALICE]),
  );
  assert.deepEqual(row, { user_id: ALICE, color: '#0d3a35', icon: '☕' });
  const defaulted = await asRole('authenticated', ALICE, async () =>
    one(`INSERT INTO categories (name) VALUES ('Snacks') RETURNING user_id`),
  );
  assert.equal(defaulted.user_id, ALICE);
});

await check('every existing user gets a Free subscription row', async () => {
  const row = await one(`SELECT count(*)::int AS n, count(*) FILTER (WHERE plan = 'free')::int AS free FROM subscriptions`);
  assert.deepEqual(row, { n: 4, free: 4 });
});

await check('get_user_plan works for the service role and is denied to users', async () => {
  const plan = await asRole('service_role', null, async () => one(`SELECT * FROM get_user_plan($1)`, [ALICE]));
  assert.equal(plan.is_pro, false);
  await asRole('authenticated', ALICE, () =>
    assert.rejects(db.query(`SELECT * FROM get_user_plan($1)`, [BOB]), /permission denied/),
  );
});

await check('a new signup with a taken username gets a suffix instead of failing', async () => {
  await db.query(`INSERT INTO auth.users (id, email, raw_user_meta_data) VALUES ($1, 'alice2@example.com', '{"username":"alice"}')`, [
    '55555555-5555-5555-5555-555555555555',
  ]);
  const row = await one(`SELECT username FROM profiles WHERE id = '55555555-5555-5555-5555-555555555555'`);
  assert.match(row.username, /^alice_[0-9a-f]{6}$/);
});

await check('subscriptions is in the realtime publication', async () => {
  const row = await one(`SELECT count(*)::int AS n FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'subscriptions'`);
  assert.equal(row.n, 1);
});

await check('amount/title checks now reject bad new rows', async () => {
  await asRole('authenticated', ALICE, async () => {
    await assert.rejects(
      db.query(`INSERT INTO transactions (user_id, title, amount, type, date) VALUES ($1, 'Zero', 0, 'EXPENSE', current_date)`, [ALICE]),
      /transactions_amount_positive/,
    );
    await assert.rejects(
      db.query(`INSERT INTO transactions (user_id, title, amount, type, date) VALUES ($1, '  ', 5, 'EXPENSE', current_date)`, [ALICE]),
      /transactions_title_not_empty/,
    );
  });
});

await check('composite transaction indexes exist', async () => {
  const row = await one(
    `SELECT count(*)::int AS n FROM pg_indexes WHERE indexname IN ('idx_transactions_user_date', 'idx_transactions_user_category', 'idx_transactions_user_type')`,
  );
  assert.equal(row.n, 3);
});

await check('deleting a user removes all of their rows (delete-account)', async () => {
  await db.query(`INSERT INTO ai_usage_log (user_id, feature) VALUES ($1, 'categorize')`, [ALICE]);
  await db.query(`INSERT INTO ai_insights (user_id, month, insight) VALUES ($1, '2026-10', 'x')`, [ALICE]);
  await db.query(`DELETE FROM auth.users WHERE id = $1`, [ALICE]);
  for (const [table, col] of [['profiles', 'id'], ['categories', 'user_id'], ['transactions', 'user_id'],
    ['subscriptions', 'user_id'], ['ai_usage_log', 'user_id'], ['ai_insights', 'user_id']]) {
    const row = await one(`SELECT count(*)::int AS n FROM ${table} WHERE ${col} = $1`, [ALICE]);
    assert.equal(row.n, 0, `${table} still has rows`);
  }
});

