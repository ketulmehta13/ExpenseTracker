"""Evaluate the assistant's understanding: intent routing, slots and follow-ups.

Usage (from ml-service/):
    python -m training.evaluate_assistant           # evaluate and write reports/assistant/
    python -m training.evaluate_assistant --gate    # ...and fail if the test set misses a floor

Hand-written messages, some of them short conversations ("how much on swiggy this month",
then "what about last month"), labelled with the intent and, for data questions, the period,
category and merchant. dev was used while writing the rules; test was written alongside and
never used to change them. The user's categories and merchants come from the simulated
histories, and "today" is fixed (Sunday 18 October 2026).

The tools themselves are tested for exact numbers in tests/test_assistant.py.
"""

from __future__ import annotations

import argparse
import json
import statistics
from datetime import UTC, date, datetime
from pathlib import Path

from app.assistant.router import DATA_INTENTS, understand
from app.ml.recurring import merchant_key
from training.runs import record_run
from training.simulate_history import CATEGORY_IDS, EVERYDAY, RECURRING

TODAY = date(2026, 10, 18)
DATA_DIR = Path(__file__).resolve().parent / "data"
DEFAULT_REPORT_DIR = Path(__file__).resolve().parent.parent / "reports" / "assistant"
FLOORS = {"intent": 0.90, "slots": 0.85}  # on the test set
CATEGORIES = [
    {"id": category_id, "name": name.title(), "user_id": None} for name, category_id in CATEGORY_IDS.items()
]
MERCHANTS = {merchant_key(title) for titles, *_ in EVERYDAY for title in titles} | {
    merchant_key(variants[0]) for variants, *_ in RECURRING
}


def load(name: str) -> list[dict]:
    with open(DATA_DIR / f"assistant_{name}.jsonl", encoding="utf-8") as lines:
        return [json.loads(line) for line in lines if line.strip()]


def run(messages: list[str]):
    """Feed a conversation through the router, carrying memory from turn to turn."""
    previous = None
    for message in messages:
        previous = understand(message, TODAY, CATEGORIES, MERCHANTS, previous)
    return previous


def score(rows: list[dict]) -> tuple[dict, list[dict]]:
    intents, slots, follow_ups, failures = [], [], [], []
    for row in rows:
        result = run(row["messages"])
        intent_ok = result.intent == row["intent"]
        got = {
            "period": result.period.key if result.period else None,
            "category": result.category["name"] if result.category else None,
            "merchant": result.merchant,
        }
        want = {key: row[key] for key in got}
        slots_ok = None
        if row["intent"] in DATA_INTENTS:
            slots_ok = intent_ok and got == want
            slots.append(slots_ok)
        intents.append(intent_ok)
        if len(row["messages"]) > 1:
            follow_ups.append(intent_ok and slots_ok is not False)
        if not intent_ok or slots_ok is False:
            failures.append({"messages": row["messages"], "want": {"intent": row["intent"], **want},
                             "got": {"intent": result.intent, **got}})
    metrics = {
        "intent": round(statistics.fmean(intents), 4),
        "slots": round(statistics.fmean(slots), 4),
        "follow_ups": round(statistics.fmean(follow_ups), 4) if follow_ups else None,
        "messages": len(rows),
        "data_questions": len(slots),
        "conversations": len(follow_ups),
    }
    return metrics, failures


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(row) + " |" for row in rows])


def report(metrics: dict) -> str:
    results = _table(
        ["Measure", "Dev", "Test"],
        [
            ["Intent accuracy", f"{metrics['dev']['intent']:.3f}", f"**{metrics['test']['intent']:.3f}**"],
            ["Data questions with every slot right (period, category, merchant)",
             f"{metrics['dev']['slots']:.3f}", f"**{metrics['test']['slots']:.3f}**"],
            ["Follow-ups understood", f"{metrics['dev']['follow_ups']:.3f}",
             f"**{metrics['test']['follow_ups']:.3f}**"],
        ],
    )
    failures = _table(
        ["Conversation", "Expected", "Got"],
        [[" → ".join(f["messages"]), json.dumps(f["want"]), json.dumps(f["got"])]
         for f in metrics["test_failures"]],
    ) if metrics["test_failures"] else "None."
    gate = _table(["Check (test set)", "Result"],
                  [[name, "pass" if ok else "**FAIL**"] for name, ok in metrics["gate"].items()])
    return f"""# Assistant understanding: evaluation report

Generated by `python -m training.evaluate_assistant` on {metrics['generated_at']}. Do not edit by hand.

{metrics['dev']['messages']} dev and {metrics['test']['messages']} test examples (each a message or a short
conversation), relative to {TODAY:%A %d %B %Y}. Dev was used while writing the rules; test never was.

{results}

## Every test failure

{failures}

## Evaluation gate

{gate}
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate the assistant's routing and slots.")
    parser.add_argument("--report-dir", type=Path, default=DEFAULT_REPORT_DIR)
    parser.add_argument("--gate", action="store_true", help="fail if the test set misses a floor")
    args = parser.parse_args(argv)

    metrics: dict = {"generated_at": datetime.now(UTC).isoformat(timespec="seconds")}
    for split in ("dev", "test"):
        metrics[split], failures = score(load(split))
        if split == "test":
            metrics["test_failures"] = failures
        print(f"{split:<5} intent {metrics[split]['intent']:.3f}  slots {metrics[split]['slots']:.3f}"
              f"  follow-ups {metrics[split]['follow_ups']:.3f}")
    test = metrics["test"]
    metrics["gate"] = {f"{name} >= {floor} (got {test[name]:.3f})": test[name] >= floor
                       for name, floor in FLOORS.items()}
    args.report_dir.mkdir(parents=True, exist_ok=True)
    (args.report_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    (args.report_dir / "report.md").write_text(report(metrics), encoding="utf-8")
    print(f"reports: {args.report_dir}")
    headline = {key: test[key] for key in ("intent", "slots", "follow_ups")}
    record_run("assistant", args.report_dir, {}, headline)
    failed = [name for name, ok in metrics["gate"].items() if not ok]
    for name in failed:
        print(f"FAILED evaluation gate: {name}")
    return 1 if args.gate and failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
