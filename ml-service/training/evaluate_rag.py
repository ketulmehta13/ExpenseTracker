"""Evaluate help-center retrieval: keyword vs embedding vs hybrid search, and two chunkings.

Usage (from ml-service/):
    python -m training.evaluate_rag           # evaluate and write reports/rag/
    python -m training.evaluate_rag --gate    # ...and fail if the test set misses a floor

Hand-written questions, each labelled with the article(s) that answer it, plus off-topic
questions that should be declined:
- dev: used to compare designs and choose the decline threshold (app/rag/retriever.py);
- test: written alongside, never used for any choice. This is the honest number.

Metrics, at article level (an article counts once, at the rank of its best section):
- hit@1 and hit@3: the right article is first / in the top three;
- MRR@5: mean of 1 / rank of the first right article (0 if not in the top five);
- decline accuracy: in-scope questions answered and off-topic ones declined.
"""

from __future__ import annotations

import argparse
import json
import statistics
from datetime import UTC, datetime
from pathlib import Path

from app.config import Settings
from app.rag.embeddings import load_embedder
from app.rag.knowledge import fixed_size_chunks, load_chunks
from app.rag.retriever import DECLINE_BELOW, HelpIndex, ranked_articles

DATA_DIR = Path(__file__).resolve().parent / "data"
DEFAULT_REPORT_DIR = Path(__file__).resolve().parent.parent / "reports" / "rag"
MODES = ("bm25", "dense", "hybrid")
FLOORS = {"hit@1": 0.80, "hit@3": 0.90, "decline_accuracy": 0.85}  # hybrid, section chunks, test set


def load(name: str) -> list[dict]:
    with open(DATA_DIR / f"help_{name}.jsonl", encoding="utf-8") as lines:
        return [json.loads(line) for line in lines if line.strip()]


def retrieval_metrics(index: HelpIndex, rows: list[dict], mode: str) -> tuple[dict, list[dict]]:
    hits1, hits3, reciprocal, misses = [], [], [], []
    for row in rows:
        if not row["articles"]:
            continue
        articles = ranked_articles(index.search(row["question"], k=15, mode=mode))[:5]
        rank = next((i for i, article in enumerate(articles, start=1) if article in row["articles"]), None)
        hits1.append(rank == 1)
        hits3.append(rank is not None and rank <= 3)
        reciprocal.append(1 / rank if rank else 0.0)
        if rank != 1:
            misses.append({"question": row["question"], "expected": row["articles"], "got": articles[:3]})
    metrics = {
        "hit@1": round(statistics.fmean(hits1), 4),
        "hit@3": round(statistics.fmean(hits3), 4),
        "mrr@5": round(statistics.fmean(reciprocal), 4),
        "questions": len(hits1),
    }
    return metrics, misses


def decline_accuracy(index: HelpIndex, rows: list[dict], threshold: float) -> float:
    correct = [(index.top_similarity(row["question"]) >= threshold) == bool(row["articles"]) for row in rows]
    return round(statistics.fmean(correct), 4)


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(row) + " |" for row in rows])


def report(metrics: dict) -> str:
    rows = []
    for chunking in ("sections", "windows"):
        for mode in MODES:
            dev, test = metrics["dev"][chunking][mode], metrics["test"][chunking][mode]
            bold = "**" if (chunking, mode) == ("sections", "hybrid") else ""
            rows.append([f"{bold}{chunking}, {mode}{bold}", f"{dev['hit@1']:.3f}", f"{dev['hit@3']:.3f}",
                         f"{test['hit@1']:.3f}", f"{test['hit@3']:.3f}", f"{test['mrr@5']:.3f}"])
    header = ["Chunking, retriever", "Dev hit@1", "Dev hit@3", "Test hit@1", "Test hit@3", "Test MRR@5"]
    results = _table(header, rows)
    sweep = _table(["Threshold", "Dev decline accuracy"],
                   [[str(t), f"{accuracy:.3f}"] for t, accuracy in metrics["dev_threshold_sweep"].items()])
    misses = _table(
        ["Question", "Expected", "Top three"],
        [[m["question"], ", ".join(m["expected"]), ", ".join(m["got"])] for m in metrics["test_misses"]],
    )
    gate = _table(["Check (test set)", "Result"],
                  [[name, "pass" if ok else "**FAIL**"] for name, ok in metrics["gate"].items()])
    dev_questions = metrics["dev"]["sections"]["hybrid"]["questions"]
    test_questions = metrics["test"]["sections"]["hybrid"]["questions"]
    return f"""# Help-center retrieval: evaluation report

Generated by `python -m training.evaluate_rag` on {metrics['generated_at']}. Do not edit by hand.

{metrics['chunks']} section chunks (or {metrics['windows']} fixed-size windows) from {metrics['articles']}
articles. Embeddings: `{metrics['embedding_model']}`. Questions: {dev_questions} dev and {test_questions} test
in-scope, plus off-topic ones for declining.

{results}

## Declining off-topic questions

A question is declined when its embedding similarity to every help section is below
{DECLINE_BELOW}, a threshold chosen on the dev questions:

{sweep}

On the test questions, {metrics['test_decline_accuracy']:.1%} were handled correctly (answered or declined).

## Test questions where the right article wasn't first (hybrid, sections)

{misses if metrics['test_misses'] else 'None.'}

## Evaluation gate

{gate}
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate help-center retrieval.")
    parser.add_argument("--report-dir", type=Path, default=DEFAULT_REPORT_DIR)
    parser.add_argument("--gate", action="store_true", help="fail if the test set misses a floor")
    args = parser.parse_args(argv)

    settings = Settings.from_env()
    embedder = load_embedder(settings.embedding_model, settings.embedding_cache_dir)
    if embedder is None:
        print("The embedding model is unavailable, so dense and hybrid search can't be evaluated.")
        return 2
    chunks = load_chunks(settings.knowledge_dir)
    indexes = {
        "sections": HelpIndex(chunks, embedder),
        "windows": HelpIndex(fixed_size_chunks(chunks), embedder),
    }

    metrics: dict = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "embedding_model": settings.embedding_model,
        "articles": len({chunk.article for chunk in chunks}),
        "chunks": len(chunks),
        "windows": len(indexes["windows"].chunks),
    }
    for split in ("dev", "test"):
        rows = load(split)
        metrics[split] = {}
        for chunking, index in indexes.items():
            metrics[split][chunking] = {}
            for mode in MODES:
                result, misses = retrieval_metrics(index, rows, mode)
                metrics[split][chunking][mode] = result
                if (split, chunking, mode) == ("test", "sections", "hybrid"):
                    metrics["test_misses"] = misses
                scores = "  ".join(f"{name} {result[name]:.3f}" for name in ("hit@1", "hit@3", "mrr@5"))
                print(f"{split:<4} {chunking:<8} {mode:<6} {scores}")
    sections = indexes["sections"]
    metrics["dev_threshold_sweep"] = {
        str(t): decline_accuracy(sections, load("dev"), t) for t in (0.5, 0.55, 0.6, 0.65, 0.7)
    }
    metrics["test_decline_accuracy"] = decline_accuracy(sections, load("test"), DECLINE_BELOW)
    print(f"decline accuracy at {DECLINE_BELOW}: dev sweep {metrics['dev_threshold_sweep']},"
          f" test {metrics['test_decline_accuracy']:.3f}")

    test = {**metrics["test"]["sections"]["hybrid"], "decline_accuracy": metrics["test_decline_accuracy"]}
    metrics["gate"] = {f"{name} >= {floor} (got {test[name]:.3f})": test[name] >= floor
                       for name, floor in FLOORS.items()}
    args.report_dir.mkdir(parents=True, exist_ok=True)
    (args.report_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    (args.report_dir / "report.md").write_text(report(metrics), encoding="utf-8")
    print(f"reports: {args.report_dir}")
    failed = [name for name, ok in metrics["gate"].items() if not ok]
    for name in failed:
        print(f"FAILED evaluation gate: {name}")
    return 1 if args.gate and failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
